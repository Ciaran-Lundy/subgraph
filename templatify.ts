/* eslint-disable @typescript-eslint/no-var-requires */
const Handlebars = require("handlebars");
const fs = require("fs-extra");
const path = require("path");
const yaml = require("js-yaml");
const { t } = require("typy");

Handlebars.registerHelper("ifEquals", function(arg1, arg2, options) {
  return arg1 === arg2 ? options.fn(this) : options.inverse(this);
});

function getNetworkNameForSubgraph() {
  switch (process.env.SUBGRAPH) {
    case "livepeer/arbitrum-one":
      return "arbitrum-one";
    case "livepeer/arbitrum-goerli":
      return "arbitrum-goerli";
    default:
      return null;
  }
}

(async () => {
  const networksFilePath = path.join(__dirname, "networks.yaml");
  const networks = yaml.load(
    await fs.readFile(networksFilePath, { encoding: "utf-8" })
  );

  const networkName = process.env.NETWORK_NAME || getNetworkNameForSubgraph();
  const network = t(networks, networkName).safeObject;

  if (t(network).isFalsy) {
    throw new Error(
      'Please set either a "NETWORK_NAME" or a "SUBGRAPH" environment variable'
    );
  }

  const subgraphTemplateFilePath = path.join(
    __dirname,
    "subgraph.template.yaml"
  );
  const source = await fs.readFile(subgraphTemplateFilePath, "utf-8");
  const template = Handlebars.compile(source);
  const result = template(network);
  await fs.writeFile(path.join(__dirname, "subgraph.yaml"), result);

  console.log("🎉 subgraph.yaml successfully generated");

  // Contract addresses for mapping code, so they are not hand-maintained in
  // helpers.ts alongside networks.yaml
  const hex = (address?: string) => (address ? `0x${address}` : "");
  const constants = {
    BONDING_MANAGER_ADDRESS: hex(network.contracts.bondingManager.address),
    ROUNDS_MANAGER_ADDRESS: hex(network.contracts.roundsManager.address),
    MINTER_ADDRESS: hex(network.contracts.minter.address),
    UNISWAP_V3_DAI_ETH_POOL_ADDRESS: hex(
      t(network, "uniswapV3Pools.daiEth").safeString
    ),
    UNISWAP_V3_LPT_ETH_POOL_ADDRESS: hex(
      t(network, "uniswapV3Pools.lptEth").safeString
    ),
  };
  const addresses = [
    `// Generated by templatify.ts from networks.yaml (${networkName}). Do not edit.`,
    `// An empty string means the contract is not deployed on this network.`,
    ...Object.entries(constants).map(
      ([name, value]) => `export const ${name} = "${value}";`
    ),
    "",
  ].join("\n");
  await fs.writeFile(path.join(__dirname, "utils", "addresses.ts"), addresses);

  console.log("🎉 utils/addresses.ts successfully generated");
})();
